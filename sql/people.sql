-- Every one of these read players.user_id. They now hop through person_id. The
-- bodies are otherwise unchanged, so the ~15 policies that call them need no
-- edit at all — which is the whole reason this project put them in functions.

CREATE OR REPLACE FUNCTION public.is_own_player(pid integer)
    RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
  SELECT EXISTS (
    SELECT 1 FROM players p
    JOIN people pe ON pe.id = p.person_id
    WHERE p.id = pid AND pe.user_id = auth.uid()
  );
$$;

CREATE OR REPLACE FUNCTION public.is_club_member(cid integer)
    RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
  SELECT EXISTS (
    SELECT 1 FROM players p
    JOIN people pe ON pe.id = p.person_id
    WHERE p.club_id = cid AND pe.user_id = auth.uid() AND p.status = 'active'
  );
$$;

-- Still the hardcoded seat: whoever holds players.id = 1 curates the shared
-- drill catalog. Only the hop to people changes.
CREATE OR REPLACE FUNCTION public.is_drill_admin()
    RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
  SELECT EXISTS (
    SELECT 1 FROM players p
    JOIN people pe ON pe.id = p.person_id
    WHERE p.id = 1 AND pe.user_id = auth.uid()
  );
$$;

-- can_touch_player() and can_touch_plan() are unchanged: they resolve through
-- is_club_member(), which was just rewritten under them.

CREATE OR REPLACE FUNCTION public.club_preview(code text)
    RETURNS TABLE(club_id integer, club_name text, player_id integer, player_name text, claimable boolean)
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
  SELECT c.id, c.name, p.id, pe.name, pe.user_id IS NULL
  FROM clubs c
  LEFT JOIN players p ON p.club_id = c.id
  LEFT JOIN people pe ON pe.id = p.person_id
  WHERE c.join_code = lower(btrim(code))
  ORDER BY pe.name;
$$;

-- Joining a club is now two inserts, so the interesting part is what a *claim*
-- means. Claiming used to attach your account to one roster row. It now attaches
-- it to a person, and a person can hold memberships in clubs whose join code you
-- do not have — especially after this file's name-matching backfill.
--
-- So every one of that person's memberships drops to 'pending', not just the one
-- in the club you are joining. Holding one club's join code must not silently
-- make you an active member of another club, and the original trigger already
-- said as much about a single row: "holding the join code is not the same as
-- being that person".
--
-- The "name taken in this club" check is gone with the constraint behind it. Two
-- different people with the same name in one club is legal now; they are
-- distinct rows in people with distinct slugs and faces.
CREATE OR REPLACE FUNCTION public.join_club(code text, claim_player_id integer DEFAULT NULL, display_name text DEFAULT NULL)
    RETURNS integer
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  cid INTEGER;
  uid UUID := auth.uid();
  me BIGINT;
  claimed BIGINT;
  pname TEXT;
BEGIN
  IF uid IS NULL THEN RAISE EXCEPTION 'sign in first'; END IF;

  SELECT id INTO cid FROM clubs WHERE join_code = lower(btrim(code));
  IF cid IS NULL THEN RAISE EXCEPTION 'unknown join code'; END IF;

  SELECT id INTO me FROM people WHERE user_id = uid;

  -- Already a member of this club, under whichever person is yours.
  IF me IS NOT NULL AND EXISTS (
    SELECT 1 FROM players WHERE club_id = cid AND person_id = me
  ) THEN
    RETURN cid;
  END IF;

  IF claim_player_id IS NOT NULL AND me IS NULL THEN
    UPDATE people pe
    SET user_id = uid
    FROM players p
    WHERE p.id = claim_player_id
      AND p.club_id = cid
      AND pe.id = p.person_id
      AND pe.user_id IS NULL
    RETURNING pe.id INTO claimed;

    IF claimed IS NOT NULL THEN
      UPDATE players SET status = 'pending' WHERE person_id = claimed;
      RETURN cid;
    END IF;
    -- Claimed between the preview and now, or you already had a person: fall
    -- through and join as somebody new.
  END IF;

  IF me IS NULL THEN
    pname := COALESCE(
      NULLIF(btrim(display_name), ''),
      NULLIF(btrim(auth.jwt() -> 'user_metadata' ->> 'full_name'), ''),
      'Player'
    );
    INSERT INTO people (name, user_id) VALUES (pname, uid) RETURNING id INTO me;
  END IF;

  INSERT INTO players (club_id, person_id, category, status)
  VALUES (cid, me, 3, 'pending');

  RETURN cid;
END $$;

-- Adding a guest — someone with no account, typed onto the roster by the club
-- owner — is two inserts across two tables, and the people insert cannot be
-- authorised by anything on the people row itself. So it is one function rather
-- than an RLS policy permissive enough to let any signed-in user create people
-- rows at will. useManagePlayers.createPlayer calls this.
CREATE OR REPLACE FUNCTION public.add_guest_player(cid integer, pname text, cat double precision DEFAULT 3)
    RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  pid BIGINT;
  new_player BIGINT;
BEGIN
  IF NOT is_club_admin(cid) THEN
    RAISE EXCEPTION 'only the club owner may add players';
  END IF;
  IF btrim(COALESCE(pname, '')) = '' THEN
    RAISE EXCEPTION 'a player needs a name';
  END IF;

  -- Deliberately always a new person. Matching a guest onto an existing person
  -- by name is exactly the guess this file's backfill only made because it had
  -- no alternative; going forward, claiming is how two rows become one human.
  INSERT INTO people (name) VALUES (btrim(pname)) RETURNING id INTO pid;

  INSERT INTO players (club_id, person_id, category, status)
  VALUES (cid, pid, cat, 'active')
  RETURNING id INTO new_player;

  RETURN new_player;
END $$;

-- The old players_guard_user_id() guarded three things at once. user_id is not
-- on players any more, so it splits in two along the seam.

CREATE OR REPLACE FUNCTION public.people_guard_user_id()
    RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
BEGIN
  -- No auth.uid() means service_role or the SQL editor: your own maintenance,
  -- including unlinking a person, still works.
  IF auth.uid() IS NULL THEN RETURN NEW; END IF;

  IF NEW.user_id IS DISTINCT FROM OLD.user_id THEN
    IF OLD.user_id IS NOT NULL OR NEW.user_id <> auth.uid() THEN
      RAISE EXCEPTION
        'people.user_id may only be set to your own id, and only on an unlinked person';
    END IF;
  END IF;

  -- The URL is written once and then never again, exactly as a club's is.
  NEW.slug := OLD.slug;

  RETURN NEW;
END $$;

CREATE TRIGGER people_guard_user_id
    BEFORE UPDATE ON public.people
    FOR EACH ROW
    EXECUTE FUNCTION public.people_guard_user_id();

CREATE OR REPLACE FUNCTION public.players_guard_membership()
    RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
BEGIN
  IF auth.uid() IS NULL THEN RETURN NEW; END IF;

  IF NEW.club_id IS DISTINCT FROM OLD.club_id AND NOT is_club_admin(OLD.club_id) THEN
    RAISE EXCEPTION 'only the club owner may move a player between clubs';
  END IF;

  -- A membership never changes hands. Without this, "Members can update club
  -- players" — which exists so the roster editor can set a division — would also
  -- let a member point somebody else's membership at their own person.
  IF NEW.person_id IS DISTINCT FROM OLD.person_id THEN
    RAISE EXCEPTION 'a membership cannot be reassigned to another person';
  END IF;

  -- The one status change that is not the owner's: claiming an unclaimed person
  -- drops their memberships to 'pending'. join_club() relies on this.
  IF NEW.status IS DISTINCT FROM OLD.status
     AND NOT is_club_admin(OLD.club_id)
     AND NOT (
       NEW.status = 'pending'
       AND EXISTS (SELECT 1 FROM people WHERE id = NEW.person_id AND user_id = auth.uid())
     ) THEN
    RAISE EXCEPTION 'only the club owner may change a member''s status';
  END IF;

  RETURN NEW;
END $$;

DROP TRIGGER players_guard_user_id ON public.players;
DROP FUNCTION public.players_guard_user_id();

CREATE TRIGGER players_guard_membership
    BEFORE UPDATE ON public.players
    FOR EACH ROW
    EXECUTE FUNCTION public.players_guard_membership();

-- Deleting a membership must not delete the human — they may play elsewhere.
-- But a guest whose only membership just went is nothing but a dangling name, so
-- it goes with them. A person with an account is kept either way: they can sign
-- in tomorrow and join somewhere new, and their slug should survive that.
CREATE OR REPLACE FUNCTION public.people_drop_orphan()
    RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
BEGIN
  DELETE FROM people
  WHERE id = OLD.person_id
    AND user_id IS NULL
    AND NOT EXISTS (SELECT 1 FROM players WHERE person_id = OLD.person_id);
  RETURN NULL;
END $$;

CREATE TRIGGER people_drop_orphan
    AFTER DELETE ON public.players
    FOR EACH ROW
    EXECUTE FUNCTION public.people_drop_orphan();

