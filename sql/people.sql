ALTER TABLE public.games DROP CONSTRAINT games_player_1_name_fkey;
ALTER TABLE public.games DROP CONSTRAINT games_player_2_name_fkey;
ALTER TABLE public.games DROP CONSTRAINT games_player_1b_name_fkey;
ALTER TABLE public.games DROP CONSTRAINT games_player_2b_name_fkey;

ALTER TABLE public.games DROP COLUMN player_1_name;
ALTER TABLE public.games DROP COLUMN player_2_name;
ALTER TABLE public.games DROP COLUMN player_1b_name;
ALTER TABLE public.games DROP COLUMN player_2b_name;

