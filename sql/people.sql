-- One row per human. `players` becomes purely the club membership.
--
-- Apply with `npm run db:sql sql/people.sql`, then `npm run db:dump` and
-- `npm run db:types`. See sql/README.md.
--
-- TAKE A BACKUP FIRST. This drops players.name, players.avatar_url and the four
-- denormalised name columns on games. None of that is recoverable from what is
-- left behind, and the backfill's name-matching merge is a judgement call that
-- cannot be undone once the source names are gone.
--
-- Why:
--
-- players.club_id was NOT NULL, so the row was the person *and* the membership.
-- One person in three clubs meant three rows, three ids, three copies of the
-- same name and the same face. The public directory at /players lists rows, so
-- that person appeared three times on three cards linking to three profiles.
--
-- Two places in the app already worked around it, which is the evidence the
-- model was wrong: AvatarUpload wrote one picture to every row matching user_id
-- ("one person, one face"), and getSession() did the same fan-out for the OAuth
-- picture on every single sign-in. Both collapse to a one-row update here.
--
-- The blocker was games. Four FKs pointed at players (club_id, name), so a
-- rename cascaded into game history and the name column could not move. But
-- games already carries player_1_id / player_2_id / player_1b_id / player_2b_id
-- and every piece of ranking maths (libs/dailyScore.ts, hooks/useEloRanking.ts)
-- reads the ids, never the names. The names were display-only denormalisation,
-- so they go, and the app resolves names through the id it already has.

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. The table
-- ---------------------------------------------------------------------------

-- slug rather than a bare id in the public URL, matching clubs. slugify() and
-- the '-' || id collision suffix are the existing ones from sql/club-slug.sql;
-- there is no reserved-word list here because /players/:slug has no static
-- siblings to lose a match against.
--
-- No reserved unique index on name: two different people genuinely can share a
-- name, and the slug suffix is what keeps them apart. This is the constraint
-- players_club_name_ci_key used to enforce, dropped in step 5.
CREATE TABLE public.people (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text,
    name text NOT NULL,
    avatar_url text,
    user_id uuid UNIQUE REFERENCES auth.users (id),
    is_public boolean NOT NULL DEFAULT true,
    -- Dropped at the end of this file. It only exists so step 3 can map a
    -- players row back to the person the backfill folded it into.
    src_gkey text,
    CONSTRAINT people_name_check CHECK (char_length(btrim(name)) >= 1)
);

ALTER TABLE public.people ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------------
-- 2. Backfill: which player rows are the same human
-- ---------------------------------------------------------------------------

-- The rule, in order of confidence:
--
--   1. Same user_id  -> same person. Proof, not a guess. Wins over everything,
--      including two different names ("Juan" in one club, "JC" in another).
--   2. An unlinked row whose name matches exactly one linked person -> that
--      person. The common case: an admin typed you onto a roster before you
--      signed up.
--   3. Unlinked rows sharing a name, none of them linked -> one person.
--   4. Unlinked rows sharing a name with *two or more different* user_ids ->
--      one person each. Two humans demonstrably share this name, so there is
--      nothing to attribute the unlinked row to. Left separate on purpose.
--
-- Rule 3 is the one that can be wrong: two different Juan Garcías in two clubs,
-- neither signed up, become one person. That was an explicit call — it is what
-- collapses the duplicate cards in the directory today. Read the groups before
-- committing:
--
--   SELECT gkey, array_agg(name ORDER BY id), array_agg(club_id ORDER BY id)
--   FROM ... GROUP BY gkey HAVING count(*) > 1;

CREATE TEMP TABLE grouped ON COMMIT DROP AS
WITH norm AS (
    SELECT
        id, club_id, name, avatar_url, user_id, is_public,
        lower(btrim(name)) AS nkey
    FROM public.players
),
-- Per name: how many distinct accounts claim it, and which one if there is
-- exactly one. count(DISTINCT ...) ignores NULLs, so unlinked rows do not vote.
--
-- array_agg()[1] rather than min(): there is no min()/max() aggregate for uuid
-- before Postgres 18, and this has to run on the version Supabase gives us.
by_name AS (
    SELECT
        nkey,
        count(DISTINCT user_id) AS uids,
        (array_agg(user_id) FILTER (WHERE user_id IS NOT NULL))[1] AS sole_uid
    FROM norm
    GROUP BY nkey
)
SELECT
    n.*,
    CASE
        WHEN n.user_id IS NOT NULL THEN 'u:' || n.user_id::text   -- rule 1
        WHEN b.uids = 1 THEN 'u:' || b.sole_uid::text             -- rule 2
        WHEN b.uids = 0 THEN 'n:' || n.nkey                       -- rule 3
        ELSE 'p:' || n.id::text                                   -- rule 4
    END AS gkey
FROM norm n
JOIN by_name b USING (nkey);

INSERT INTO public.people (src_gkey, name, avatar_url, user_id, is_public)
SELECT
    gkey,
    -- The linked row's spelling is the person's own; failing that, oldest wins.
    (array_agg(name ORDER BY (user_id IS NULL), id))[1],
    -- A data: URI is an upload the person chose. Anything else is the OAuth
    -- picture, which getSession() will put back on its own if it is still
    -- current. Prefer the choice.
    COALESCE(
        max(avatar_url) FILTER (WHERE avatar_url LIKE 'data:%'),
        max(avatar_url)
    ),
    (array_agg(user_id) FILTER (WHERE user_id IS NOT NULL))[1],
    -- Opting out in one club was the only way to opt out at all, so treat it as
    -- opting out entirely rather than silently re-listing them.
    bool_and(is_public)
FROM grouped
GROUP BY gkey;

-- Slugs need the id, so they land in a second pass. Same shape as the clubs
-- backfill in sql/club-slug.sql.
WITH ranked AS (
    SELECT
        id,
        public.slugify(name) AS base,
        row_number() OVER (PARTITION BY public.slugify(name) ORDER BY id) AS rn
    FROM public.people
)
UPDATE public.people p
SET slug = CASE WHEN r.rn > 1 THEN r.base || '-' || p.id ELSE r.base END
FROM ranked r
WHERE r.id = p.id;

ALTER TABLE public.people ALTER COLUMN slug SET NOT NULL;
CREATE UNIQUE INDEX people_slug_key ON public.people (slug);
ALTER TABLE public.people
    ADD CONSTRAINT people_slug_shape CHECK (slug ~ '^[a-z0-9][a-z0-9-]*$');

-- ---------------------------------------------------------------------------
-- 3. Wire players to people
-- ---------------------------------------------------------------------------

ALTER TABLE public.players ADD COLUMN person_id bigint;

UPDATE public.players pl
SET person_id = pe.id
FROM grouped g
JOIN public.people pe ON pe.src_gkey = g.gkey
WHERE pl.id = g.id;

ALTER TABLE public.players ALTER COLUMN person_id SET NOT NULL;
ALTER TABLE public.players
    ADD CONSTRAINT players_person_id_fkey
    FOREIGN KEY (person_id) REFERENCES public.people (id) ON DELETE CASCADE;

-- One membership per person per club. Replaces players_club_user_key, and says
-- the same thing about unlinked players that it could only say about linked
-- ones.
ALTER TABLE public.players
    ADD CONSTRAINT players_club_person_key UNIQUE (club_id, person_id);

CREATE INDEX players_person_idx ON public.players (person_id);

-- ---------------------------------------------------------------------------
-- 4. Games stop carrying names
-- ---------------------------------------------------------------------------

-- These four are the reason players.name could not move: ON UPDATE CASCADE from
-- players (club_id, name). The id columns beside them are not nullable for the
