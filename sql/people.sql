-- Mirrors clubs_set_slug() in sql/club-slug.sql, including the '-' || id
-- suffix. NEW.id is already populated in a BEFORE ROW trigger — column defaults
-- are applied first.
CREATE OR REPLACE FUNCTION public.people_set_slug()
    RETURNS trigger
    LANGUAGE plpgsql
    AS $$
DECLARE
    base text;
BEGIN
    IF NEW.slug IS NOT NULL AND NEW.slug <> '' THEN
        RETURN NEW;
    END IF;

    base := public.slugify(NEW.name);

    IF EXISTS (SELECT 1 FROM public.people WHERE slug = base AND id <> NEW.id) THEN
        NEW.slug := base || '-' || NEW.id;
    ELSE
        NEW.slug := base;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER people_set_slug
    BEFORE INSERT ON public.people
    FOR EACH ROW
    EXECUTE FUNCTION public.people_set_slug();

