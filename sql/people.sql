-- 8. Policies
-- ---------------------------------------------------------------------------

-- players, rewritten without the columns that left. The three dropped in step 5
-- come back reading through people.

-- The second half is what a member with a *pending* membership needs to see
-- their own row: is_club_member() requires 'active'.
--
-- Written out rather than calling is_own_player(id), for the reason already
-- recorded in sql/public-pages.sql: that function takes an integer and
-- players.id is a bigint, so the call does not resolve. Inline is the better
-- answer regardless — person_id is on the row being tested, so this needs no
-- SECURITY DEFINER hop to reach it.
CREATE POLICY "Members can view club players" ON public.players
    FOR SELECT TO authenticated
    USING (
        public.is_club_member(club_id)
        OR person_id IN (SELECT id FROM public.people WHERE user_id = auth.uid())
    );

-- Same substitution, same reason.
CREATE POLICY "Own row can be updated" ON public.players
    FOR UPDATE TO authenticated
    USING (person_id IN (SELECT id FROM public.people WHERE user_id = auth.uid()))
    WITH CHECK (person_id IN (SELECT id FROM public.people WHERE user_id = auth.uid()));

-- is_public moved to people, so it is filtered there. A membership of a public
-- club stays readable either way: results and brackets have to be able to name
-- an unlisted player. Same reasoning as the note in sql/public-pages.sql.
CREATE POLICY "Players of public clubs are readable by anyone" ON public.players
    FOR SELECT TO anon
    USING (status = 'active' AND public.is_public_club(club_id));

-- The three predicates people's own policies need. Each one reads players, and
-- players' SELECT policy reads people — written inline that is a cycle, and
-- Postgres answers it with "infinite recursion detected in policy for relation".
-- SECURITY DEFINER breaks it: the function runs as the owner, for whom players'
-- RLS does not apply. Same device as is_club_member() and is_public_club(),
-- which already exist for the same class of problem.
CREATE OR REPLACE FUNCTION public.person_shares_club(pid bigint)
    RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
  SELECT EXISTS (
    SELECT 1 FROM players p WHERE p.person_id = pid AND is_club_member(p.club_id)
  );
$$;

CREATE OR REPLACE FUNCTION public.person_is_admins_guest(pid bigint)
    RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
  SELECT EXISTS (
    SELECT 1 FROM players p WHERE p.person_id = pid AND is_club_admin(p.club_id)
  );
$$;

CREATE OR REPLACE FUNCTION public.person_in_public_club(pid bigint)
    RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
  SELECT EXISTS (
    SELECT 1 FROM players p
    WHERE p.person_id = pid AND p.status = 'active' AND is_public_club(p.club_id)
  );
$$;

-- people. Readable by anyone who shares a club with them, plus your own row
-- before any membership is active.
CREATE POLICY "Members can view people in their clubs" ON public.people
    FOR SELECT TO authenticated
    USING (user_id = auth.uid() OR public.person_shares_club(id));

-- Your name, your face, your listing. Nobody else's: the roster editor sets a
-- division, which is on players and stays there.
CREATE POLICY "Own person can be updated" ON public.people
    FOR UPDATE TO authenticated
    USING (user_id = auth.uid())
    WITH CHECK (user_id = auth.uid());

-- A guest has no account, so nobody satisfies the policy above and their name
-- would be uneditable. The club that typed them in owns that name.
CREATE POLICY "Admin can update guests in their club" ON public.people
    FOR UPDATE TO authenticated
    USING (user_id IS NULL AND public.person_is_admins_guest(id))
    WITH CHECK (user_id IS NULL);

-- No INSERT or DELETE policy on purpose. join_club() and add_guest_player() are
-- SECURITY DEFINER and create people; people_drop_orphan() removes them. A
-- permissive insert policy would let any signed-in user fill the table.

-- is_public is not a condition here, for the reason publicPlayerQuery already
-- documents: it governs whether somebody is *listed*, and a name in a bracket
-- links to their profile. The directory filters it in the query instead.
CREATE POLICY "People of public clubs are readable by anyone" ON public.people
    FOR SELECT TO anon
    USING (public.person_in_public_club(id));

