-- 5. Strip the person out of players
-- ---------------------------------------------------------------------------

-- Both were the FK target for the columns just dropped, or a uniqueness rule
-- about a column that no longer lives here.
ALTER TABLE public.players DROP CONSTRAINT players_club_name_key;
ALTER TABLE public.players DROP CONSTRAINT players_club_user_key;
DROP INDEX public.players_club_name_ci_key;

-- Policies that read the columns about to disappear. Recreated in step 8.
DROP POLICY "Members can view club players" ON public.players;
DROP POLICY "Own row can be updated" ON public.players;
DROP POLICY "Players of public clubs are readable by anyone" ON public.players;

ALTER TABLE public.players DROP COLUMN name;
ALTER TABLE public.players DROP COLUMN avatar_url;
ALTER TABLE public.players DROP COLUMN user_id;
ALTER TABLE public.players DROP COLUMN is_public;

